import express, { Router } from "express";
import { authenticate, requireRoles } from "../../middleware/authenticate.js";
import * as controller from "./delivery.controller.js";
import * as governance from "./document-governance.controller.js";

const router = Router({ mergeParams: true });
const managers = requireRoles("owner", "admin", "project_manager");
router.use(authenticate);
router.get("/summary", controller.getDeliverySummary);
router.get("/inspections", controller.listInspections);
router.post("/inspections", managers, controller.createInspection);
router.patch("/inspections/:inspectionId/status", managers, controller.updateInspectionStatus);
router.get("/ncrs", controller.listNcrs);
router.post("/ncrs", managers, controller.createNcr);
router.patch("/ncrs/:ncrId/status", managers, controller.updateNcrStatus);
router.get("/ncrs/:ncrId/capa", controller.listCapas);
router.post("/ncrs/:ncrId/capa", managers, controller.createCapa);
router.patch("/capa/:capaId/status", managers, controller.updateCapaStatus);
router.get("/safety-events", controller.listSafetyEvents);
router.post("/safety-events", managers, controller.createSafetyEvent);
router.patch("/safety-events/:eventId/status", managers, controller.updateSafetyStatus);
router.get("/rfis", controller.listRfis);
router.post("/rfis", managers, controller.createRfi);
router.patch("/rfis/:rfiId/submit", managers, controller.submitRfi);
router.patch("/rfis/:rfiId/respond", managers, controller.respondRfi);
router.get("/submittals", controller.listSubmittals);
router.post("/submittals", managers, controller.createSubmittal);
router.patch("/submittals/:submittalId/submit", managers, controller.submitSubmittal);
router.patch("/submittals/:submittalId/review", managers, controller.reviewSubmittal);
router.get("/documents", controller.listDocuments);
router.post("/documents", managers, controller.createDocument);
router.post("/documents/:documentId/versions", managers, controller.addDocumentVersion);
router.post("/documents/:documentId/files", managers, express.raw({ type: ["application/pdf", "image/png", "image/jpeg", "image/webp", "application/ifc"], limit: "25mb" }), controller.uploadDocumentFile);
router.post("/documents/:documentId/uploads", managers, controller.createDocumentUpload);
router.get("/documents/:documentId/uploads/:uploadId", managers, controller.getDocumentUpload);
router.put("/documents/:documentId/uploads/:uploadId/parts/:partNumber", managers, express.raw({ type: "application/octet-stream", limit: "5mb" }), controller.uploadDocumentPart);
router.post("/documents/:documentId/uploads/:uploadId/complete", managers, controller.completeDocumentUpload);
router.delete("/documents/:documentId/uploads/:uploadId", managers, controller.abortDocumentUpload);
router.get("/documents/:documentId/files/:assetId/download", controller.downloadDocumentFile);
router.patch("/documents/:documentId/approval", managers, controller.updateDocumentApproval);
router.get("/document-governance/retention", governance.getDocumentRetentionPolicy);
router.put("/document-governance/retention", managers, governance.updateDocumentRetentionPolicy);
router.get("/document-governance/retention/evaluation", governance.evaluateDocumentRetention);
router.get("/document-governance/legal-holds", governance.listDocumentLegalHolds);
router.post("/documents/:documentId/legal-holds", managers, governance.placeDocumentLegalHold);
router.post("/documents/:documentId/legal-holds/:holdId/release", managers, governance.releaseDocumentLegalHold);
export default router;
